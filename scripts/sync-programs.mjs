#!/usr/bin/env node
/*
 * Syncs the real download figures for the author's own programs from the
 * GitHub Releases API into src/data/programReleases.ts.
 *
 * Why this exists: the site's click counter (KV) only sees clicks that
 * happen on the site itself, so the author's own apps could show a small
 * fraction of their true numbers while the third-party cards (seeded
 * earlier from their releases) show full figures. This script sums the
 * real per-asset download counts of every release, and records the older
 * releases with their links so the card can render a
 * "previous versions" list — for the author's programs only.
 *
 * Run:   node scripts/sync-programs.mjs
 * Needs: an authenticated `gh` CLI (it shells out to `gh api`, so private
 *        repositories work without putting a token anywhere).
 */
import { execSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')

/**
 * The author's own programs only ("my projects"). `current` is the version
 * the site's main buttons already link — releases matching it are counted
 * into the baseline but not repeated in the previous-versions list.
 * Repos with no releases yet stay commented; add a line and re-run when
 * they publish one, and the card picks the data up with no UI change.
 */
const SOURCES = {
  'edms-archive-pro': { repo: 'zeiad6/Edms-archive', current: '1.0.6' },
  // 'edms-archive-android': { repo: 'zeiad6/Edms-archive-Android', current: '1.0.1' },
  // verityscope: { repo: 'zeiad6/VerityScope', current: '0.4.0' },
}

/** Auto-update metadata, not a file a human asked to download. */
const AUX = /\.(ya?ml|blockmap|json|sig|sha256|sha512)$/i

const gh = (path) => JSON.parse(execSync(`gh api "${path}"`, { encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 }))

function fmtSize(bytes) {
  if (bytes >= 1048576) return `${(bytes / 1048576).toFixed(1)} MB`
  if (bytes >= 1024) return `${Math.round(bytes / 1024)} KB`
  return `${bytes} B`
}

const out = {}
for (const [slug, cfg] of Object.entries(SOURCES)) {
  let releases
  try {
    releases = gh(`repos/${cfg.repo}/releases?per_page=100`)
  } catch (err) {
    console.error(`! ${slug}: GitHub fetch failed (${String(err.message).split('\n')[0]}) — left unchanged`)
    continue
  }

  let baseline = 0
  const versions = []
  for (const r of releases) {
    if (r.draft) continue
    const files = (r.assets ?? [])
      .filter((a) => !AUX.test(a.name))
      .map((a) => ({
        name: a.name,
        href: a.browser_download_url,
        size: fmtSize(a.size),
        downloads: a.download_count,
      }))
    if (files.length === 0) continue
    baseline += files.reduce((n, f) => n + f.downloads, 0)
    const tag = String(r.tag_name).replace(/^v/, '')
    if (tag !== cfg.current) {
      versions.push({ version: tag, date: String(r.published_at).slice(0, 10), files })
    }
  }
  versions.sort((a, b) => `${b.date}${b.version}`.localeCompare(`${a.date}${a.version}`))
  out[slug] = { baseline, versions, syncedAt: new Date().toISOString().slice(0, 10) }
  console.log(`✓ ${slug}: baseline=${out[slug].baseline}, previous versions=${versions.length}`)
}

const banner = `/* ------------------------------------------------------------------ *
 * AUTO-GENERATED by scripts/sync-programs.mjs — do not edit by hand.
 * Real release figures for the author's own programs, read from the
 * GitHub Releases API: the summed download counts of every release file
 * (the "baseline" the card adds to the site's own click counter), and the
 * older releases with their links (the previous-versions list).
 * Re-run the script after publishing a release; nothing else to change.
 * ------------------------------------------------------------------ */`

writeFileSync(
  resolve(ROOT, 'src/data/programReleases.ts'),
  `${banner}

export type ReleaseFile = { name: string; href: string; size: string; downloads: number }
export type ProgramRelease = { version: string; date: string; files: ReleaseFile[] }
export type ProgramReleaseInfo = {
  /** Sum of real downloads of every release file across all mirrors known to the API. */
  baseline: number
  /** Older releases (the current one is not listed), newest first. */
  versions: ProgramRelease[]
  syncedAt: string
}

export const programReleases: Record<string, ProgramReleaseInfo> = ${JSON.stringify(out, null, 2)}

/** Real downloads recorded on the release mirrors (0 when unknown). */
export function baselineFor(slug: string): number {
  return programReleases[slug]?.baseline ?? 0
}

/** Older releases with their links — the author's own programs only. */
export function releasesFor(slug: string): ProgramReleaseInfo | undefined {
  return programReleases[slug]
}
`,
)

console.log(`\nWrote src/data/programReleases.ts (${Object.keys(out).length} programs)`)
