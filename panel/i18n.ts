export const t = (lang: Lang, key: string): string => I18N[lang][key] ?? ''

/** وقت نسبي مختصر: الآن / 5د / 3س / 2ي. */
export const ago = (lang: Lang, at: number): string => {
  const s = Math.max(0, Math.floor((Date.now() - at) / 1000))
  if (s < 60) return t(lang, 'timeNow')
  const m = Math.floor(s / 60)
  if (m < 60) return `${m}${t(lang, 'timeMin')}`
  const h = Math.floor(m / 60)
  if (h < 24) return `${h}${t(lang, 'timeHour')}`
  return `${Math.floor(h / 24)}${t(lang, 'timeDay')}`
}
